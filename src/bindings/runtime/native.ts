  dbs_set_sync_call: { args: ["ptr"], returns: "void" },
  dbs_context_close: { args: [], returns: "void" },
  dbs_counters: { args: [], returns: "ptr" },
  dbs_version: { args: [], returns: "cstring" },
  dbs_capi_table: { args: ["ptr"], returns: "ptr" },
  dbs_exception_flag: { args: [], returns: "ptr" },
  dbs_take_exception: { args: [], returns: "ptr" },

  dbs_job_open: { args: ["ptr", "usize", "bool", "ptr"], returns: "ptr" },
  dbs_job_get_or_create_from_cache: { args: ["ptr", "ptr", "usize", "bool", "ptr"], returns: "ptr" },
  dbs_job_connect: { args: ["ptr"], returns: "ptr" },
  dbs_job_query: { args: ["ptr", "ptr", "usize"], returns: "ptr" },
