const paths = nativePaths();

// libduckdb first, by absolute path, so the shim's own dependency on it resolves
// to this already-loaded image. The binding calls it only through the shim.
const library = dlopen(paths.libPath, { duckdb_library_version: { args: [], returns: "ptr" } });
const shimLibrary = dlopen(paths.shimPath, shimAbi).symbols;

/** The wrappers' addresses, `capi` entries first, then `byValue` ones. */
const addresses = (() => {
  const count = new BigUint64Array(1);
  const table = shimLibrary.dbs_capi_table(count) as Pointer;
  const expected = Object.keys(capi).length + Object.keys(byValue).length;
  if (Number(count[0]) !== expected) {
    throw new Error(`The shim at ${paths.shimPath} has ${count[0]} C API wrappers; this binding needs ${expected}.`);
  }
  return new BigUint64Array(toArrayBuffer(table, 0, expected * 8));
})();

/** `table` with each function's wrapper address, starting at `offset` in the address table. */
function located<T extends Record<string, FFIFunction>>(table: T, offset: number): T {
  return Object.fromEntries(
    Object.entries(table).map(([name, fn], i) => [name, { ...fn, ptr: addresses[offset + i] }]),
  ) as T;
}

/** The calling JS thread's C++ exception flag, set by a wrapper that caught one. */
const exceptionFlag = new Int32Array(toArrayBuffer(shimLibrary.dbs_exception_flag() as Pointer, 0, 4));
const rawCapi = linkSymbols(located(capi, 0)).symbols;
const rawByValue = linkSymbols(located(byValue, Object.keys(capi).length)).symbols;

/** Throws the C++ exception the last call caught, with DuckDB's message for it. */
function raise(): never {
  const pointer = shimLibrary.dbs_take_exception() as Pointer | null;
  let what: string | null = null;
  if (pointer !== null) {
    try {
      what = new CString(pointer).toString();
    } finally {
      rawCapi.duckdb_free(pointer);
    }
  }
  throw new Error(exceptionMessage(what));
}

export const duckdb = guardCapi(rawCapi, exceptionFlag, raise);
export const shim = { ...guardByValue(rawByValue, exceptionFlag, raise), ...shimLibrary };
export const libraryPath = paths.libPath;
export const shimPath = paths.shimPath;

/** The versions a crash report and diagnostics() name. */
export const versions = {
  package: packageJson.version,
  duckdb: new CString(library.symbols.duckdb_library_version() as Pointer).toString(),
  bun: Bun.version,
  shim: String(shim.dbs_version()),
} as const;

debug(`loaded libduckdb ${versions.duckdb} from ${libraryPath}, shim ${versions.shim} from ${shimPath}`);

const CRASH_HANDLER_STATUS = ["installed", "failed: no alternate signal stack", "failed: sigaction"] as const;

/** The fatal-signal handler's state: native/ABI.md "Diagnostics". */
export const crashHandler: "disabled" | (typeof CRASH_HANDLER_STATUS)[number] = flags.crashHandler
  ? installCrashHandler()
  : "disabled";

function installCrashHandler(): (typeof CRASH_HANDLER_STATUS)[number] {
  const header = Buffer.from(
    `package ${versions.package}, duckdb ${versions.duckdb}, bun ${versions.bun}, shim ${versions.shim}`,
  );
  const status = CRASH_HANDLER_STATUS[shim.dbs_install_crash_handler(header, header.length)] ?? "failed: sigaction";
  // Queries work without the handler, so a failed install is not an error: diagnostics() reports it.
  debug(`crash handler ${status}`);
  return status;
}
