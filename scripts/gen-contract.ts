// Generates src/bindings/generated/contract.ts from the @duckdb/node-bindings
// contract the vendored @duckdb/node-api is built against
// (vendor/node-api/node-bindings.d.ts): the runtime enums and constants the
// declaration file only declares, and a type-only re-export of every other
// declared type.
//
//   bun run gen:contract
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const CONTRACT = join(ROOT, "vendor", "node-api", "node-bindings.d.ts");
const OUT = join(ROOT, "src", "bindings", "generated", "contract.ts");

const source = await Bun.file(CONTRACT).text();

const enums = [...source.matchAll(/^export enum (\w+) \{[\s\S]*?^\}/gm)].map((match) => match[0]);
if (enums.length === 0) throw new Error(`No enums found in ${CONTRACT}`);
const enumNames = new Set([...source.matchAll(/^export enum (\w+)/gm)].map((match) => match[1]));

const constants = [...source.matchAll(/^export const (\w+): (\w+);/gm)].map(([, name]) => name);
// The only declared constant is sizeof_bool, sizeof(bool) in the C API, which is
// 1 on every platform DuckDB ships for.
const CONSTANT_VALUES: Record<string, string> = { sizeof_bool: "1" };
for (const name of constants) {
  if (!(name in CONSTANT_VALUES)) throw new Error(`No value known for the contract constant ${name}`);
}

const types = [...source.matchAll(/^export (?:interface|type) (\w+)/gm)]
  .map((match) => match[1])
  .filter((name) => !enumNames.has(name));

await Bun.write(
  OUT,
  [
    "// Generated by scripts/gen-contract.ts from vendor/node-api/node-bindings.d.ts; do not edit.",
    "",
    ...constants.map((name) => `export const ${name} = ${CONSTANT_VALUES[name]};`),
    "",
    enums.join("\n\n"),
    "",
    "export type {",
    ...types.map((name) => `  ${name},`),
    '} from "../../../vendor/node-api/node-bindings.d.ts";',
    "",
  ].join("\n"),
);
await Bun.$`${join(ROOT, "node_modules", ".bin", "biome")} check --write ${OUT}`.quiet();
console.log(`contract: ${enums.length} enums, ${constants.length} constants, ${types.length} types`);
