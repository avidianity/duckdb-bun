// Vendors DuckDB's machine-readable C API spec (api_spec/v1 in duckdb/duckdb) at
// the pinned DuckDB version into vendor/duckdb-api-spec/. duckdb.h is generated
// from these YAML files upstream; scripts/gen-ffi.ts generates our FFI symbol
// table, struct layouts and the C++ wrappers from them.
//
//   bun run scripts/vendor-api-spec.ts
import { rm } from "node:fs/promises";
import { join } from "node:path";
import { DUCKDB_VERSION } from "../src/version.ts";

const ROOT = join(import.meta.dir, "..");
const OUT = join(ROOT, "vendor", "duckdb-api-spec");
const TAG = `v${DUCKDB_VERSION}`;
const KEEP = (path: string) => path === "api_spec/README.md" || path.startsWith("api_spec/v1/");

async function getJson(url: string): Promise<unknown> {
  const response = await fetch(url, { headers: { accept: "application/vnd.github+json" } });
  if (!response.ok) throw new Error(`GET ${url} answered ${response.status} ${response.statusText}`);
  return response.json();
}

const commit = (await getJson(`https://api.github.com/repos/duckdb/duckdb/commits/${TAG}`)) as { sha: string };
const tree = (await getJson(`https://api.github.com/repos/duckdb/duckdb/git/trees/${commit.sha}?recursive=1`)) as {
  truncated: boolean;
  tree: { path: string; type: string }[];
};
if (tree.truncated) throw new Error("GitHub truncated the tree listing; the spec list would be incomplete");
const paths = tree.tree.filter((entry) => entry.type === "blob" && KEEP(entry.path)).map((entry) => entry.path);
if (paths.length === 0) throw new Error(`No api_spec/v1 files at duckdb ${TAG}`);

await rm(OUT, { recursive: true, force: true });
await Promise.all(
  paths.map(async (path) => {
    const url = `https://raw.githubusercontent.com/duckdb/duckdb/${commit.sha}/${path}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`GET ${url} answered ${response.status} ${response.statusText}`);
    await Bun.write(join(OUT, path.slice("api_spec/".length)), await response.bytes());
  }),
);
await Bun.write(
  join(OUT, "SOURCE.md"),
  [
    "# DuckDB C API spec",
    "",
    "Generated by `scripts/vendor-api-spec.ts`; do not edit.",
    `Copied from https://github.com/duckdb/duckdb/tree/${commit.sha}/api_spec (tag ${TAG}), MIT licensed like DuckDB itself.`,
    "",
  ].join("\n"),
);
console.log(`Vendored ${paths.length} files of duckdb ${TAG} (${commit.sha}) api_spec into vendor/duckdb-api-spec/`);
